// PERSONA LAUNCH GO-LIVE — THE GPL-3.0 SOURCE OFFER for public/device/prover.js (A-GPL-SOURCE-OFFER, owner decision J:
// publish). Why it exists: prover.js bundles snarkjs and ffjavascript (GPL-3.0), so the file as a whole is GPL-3.0, and
// serving it to every visitor is distribution. GPL-3.0 section 6(d) is met by "offering equivalent access to the
// Corresponding Source in the same way through the same place at no further charge": the app serves, beside prover.js,
// at /device/source/, the Totem files the bundle was built from EXACTLY as built (byte for byte, each with its sha256),
// the build script and config that control the build, the GPL-3.0 text, the bundled packages' versions with upstream
// source links, the commit, and a short notice page. Counsel review before commercial distribution is still the
// recommendation (SECURITY-POSTURE F15).
//
// Nothing here is hand-kept where it could drift: which Totem files the offer serves is READ from esbuild's metafile for
// the bundle (every input outside node_modules), the bundled packages and their versions come from the same metafile and
// the packages' own package.json, and the files are copied from the committed sources at build time. scripts/build-device.mjs
// writes the offer on every build and FAILS the build (deleting prover.js) when the offer does not match the bundle: a
// sixth Totem file cannot ride prover.js unoffered, a missing file or a missing GPL text stops the build, and a served
// byte that differs from its source stops it too. scripts/smoke-deployed.mjs check 11 re-reads the offer from a
// deployment with deployedOfferProblems(); scripts/unit-prover.mjs G1-G8 check and mutate each guard.
//
// PURE except readCommit() (reads .git), writeOffer() (writes the folder) and servedProblems() (reads it back): the
// generator takes bytes in and gives bytes out, so every guard is testable without a build.
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";

/** where the app serves the offer (public/device/source/ — generated by scripts/build-device.mjs, gitignored) */
export const OFFER_URL = "/device/source/";
export const OFFER_DIR_NAME = "source";
/** every source file is served with this suffix: Next's static server maps ".ts" to video/mp2t, ".txt" to text/plain */
export const SERVED_SUFFIX = ".txt";
export const LICENSE_TEXT_NAME = "GPL-3.0.txt";
export const MANIFEST_NAME = "manifest.json";
export const OFFER_SCHEMA = "layers-gpl-source/1";
/** the two GPL-3.0 packages the offer names by their upstream repositories (a git tag per version) */
export const UPSTREAM = Object.freeze({ snarkjs: "https://github.com/iden3/snarkjs", ffjavascript: "https://github.com/iden3/ffjavascript" });
/** the Totem files that CONTROL the build (GPL-3.0 section 1: "the scripts used to control those activities"). Not bundle
 *  inputs, so not in the metafile; served beside the inputs with the same byte-for-byte rule. */
export const BUILD_FILES = Object.freeze(["scripts/build-device.mjs", "scripts/lib/gpl-source.mjs", "tsconfig.json"]);

export const sha256Hex = (b) => createHash("sha256").update(b).digest("hex");
const posix = (p) => String(p).split("\\").join("/");
/** a repo-relative path the offer may serve: letters, digits, _ - . @ and /; no absolute path, no ".." segment */
const SAFE_REL = /^(?!\/)(?!.*(?:^|\/)\.\.(?:\/|$))[A-Za-z0-9_@.\-/]+$/;
export const servedUrlOf = (rel) => OFFER_URL + rel + SERVED_SUFFIX;
const servedRelOf = (rel) => rel + SERVED_SUFFIX;

/** the npm package directory a node_modules input belongs to ("node_modules/snarkjs/node_modules/ffjavascript/x.js" →
 *  "node_modules/snarkjs/node_modules/ffjavascript"), or null */
function packageDirOf(input) {
  const p = posix(input).replace(/^\(disabled\):/, "");
  const i = p.lastIndexOf("node_modules/");
  if (i < 0) return null;
  const rest = p.slice(i + "node_modules/".length).split("/");
  const n = rest[0].startsWith("@") ? 2 : 1;
  if (rest.length < n || !rest[n - 1]) return null;
  return p.slice(0, i + "node_modules/".length) + rest.slice(0, n).join("/");
}

/**
 * PURE: the Totem files the bundle was built from — every metafile input outside node_modules, sorted, repo-relative
 * posix paths. An input that is neither a package file nor a plain repo path (a new kind of virtual input) THROWS, so an
 * unknown input fails the offer instead of slipping past it.
 */
export function layersInputsOf(metafile) {
  const inputs = Object.keys((metafile && metafile.inputs) || {});
  if (inputs.length === 0) throw new Error("the prover's metafile lists no inputs — the offer cannot say what the bundle carries");
  const out = [];
  for (const raw of inputs) {
    if (packageDirOf(raw)) continue;
    const p = posix(raw);
    if (!SAFE_REL.test(p)) throw new Error(`the prover's metafile names an input the offer cannot serve: ${JSON.stringify(p)}`);
    out.push(p);
  }
  return [...new Set(out)].sort();
}

/**
 * PURE (readPkg injected): the npm packages bundled into prover.js, from the metafile's node_modules inputs — name,
 * version, license and a source link (the upstream git tag for snarkjs / ffjavascript, the npm registry page of that
 * exact version otherwise: the registry tarball is the package's source). Sorted by name then version.
 */
export function bundledPackagesOf(metafile, readPkg) {
  const dirs = new Set();
  for (const raw of Object.keys((metafile && metafile.inputs) || {})) {
    const d = packageDirOf(raw);
    if (d) dirs.add(d);
  }
  const out = [];
  const seen = new Set();
  for (const dir of dirs) {
    const pkg = readPkg(dir);
    if (!pkg || typeof pkg.name !== "string" || typeof pkg.version !== "string") throw new Error(`the bundled package at ${dir} has no readable name and version`);
    const key = pkg.name + "@" + pkg.version;
    if (seen.has(key)) continue;
    seen.add(key);
    const license = typeof pkg.license === "string" ? pkg.license : pkg.license && typeof pkg.license.type === "string" ? pkg.license.type : "UNKNOWN";
    out.push({ name: pkg.name, version: pkg.version, license, source: UPSTREAM[pkg.name] ? `${UPSTREAM[pkg.name]}/tree/v${pkg.version}` : `https://www.npmjs.com/package/${pkg.name}/v/${pkg.version}` });
  }
  return out.sort((a, b) => (a.name === b.name ? (a.version < b.version ? -1 : 1) : a.name < b.name ? -1 : 1));
}

/** the commit the build names: LAYERS_COMMIT (a deployed image has no .git), else .git HEAD (loose ref or packed-refs,
 *  exactly as validator/server.js gitHead does), else "unknown" */
export function readCommit(root, env = process.env) {
  if (env.LAYERS_COMMIT && String(env.LAYERS_COMMIT).trim()) return String(env.LAYERS_COMMIT).trim();
  try {
    const head = readFileSync(path.join(root, ".git", "HEAD"), "utf8").trim();
    if (!head.startsWith("ref: ")) return head;
    const ref = head.slice(5).trim();
    const loose = path.join(root, ".git", ref);
    if (existsSync(loose)) return readFileSync(loose, "utf8").trim();
    const packed = path.join(root, ".git", "packed-refs");
    if (existsSync(packed)) {
      const line = readFileSync(packed, "utf8").split(/\r?\n/).find((l) => l.endsWith(" " + ref));
      if (line) return line.split(" ")[0];
    }
  } catch {
    /* not a checkout (a deployed image) */
  }
  return "unknown";
}

const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

/** the notice page: plain HTML, NO inline script or style (the middleware's policy and the rule that a notice needs none) */
export function indexHtml(manifest) {
  const li = (e) => `      <li><a href="${esc(e.url)}">${esc(e.path)}</a> <span>(${e.bytes} bytes, sha256 <code>${esc(e.sha256)}</code>)</span></li>`;
  const pk = (p) => `      <li>${esc(p.name)} ${esc(p.version)} (${esc(p.license)}): <a href="${esc(p.source)}">${esc(p.source)}</a></li>`;
  return [
    "<!doctype html>",
    '<html lang="en">',
    "  <head>",
    '    <meta charset="utf-8" />',
    '    <meta name="viewport" content="width=device-width,initial-scale=1" />',
    "    <title>Source code of the Totem browser prover</title>",
    "  </head>",
    "  <body>",
    "    <h1>Source code of the Totem browser prover</h1>",
    `    <p>This site serves <a href="${esc(manifest.prover)}">${esc(manifest.prover)}</a>, the program your browser uses to make anonymous proofs. It contains snarkjs and ffjavascript, which are licensed under the GNU General Public License, version 3, so the file as a whole is distributed under that license. This page is the offer of its corresponding source, free of charge, from the same place as the program.</p>`,
    `    <p>The full license text: <a href="${esc(manifest.licenseText)}">${LICENSE_TEXT_NAME}</a>. The notices and the license comments of every bundled package: <a href="${esc(manifest.notices)}">${esc(manifest.notices)}</a>.</p>`,
    "    <h2>Totem files in the program, exactly as built</h2>",
    "    <ul>",
    ...manifest.files.map(li),
    "    </ul>",
    "    <h2>Files that control the build</h2>",
    "    <ul>",
    ...manifest.build.map(li),
    "    </ul>",
    "    <h2>GPL-3.0 packages, upstream source</h2>",
    "    <ul>",
    ...manifest.upstream.map(pk),
    "    </ul>",
    "    <p>snarkjs and ffjavascript are bundled from their own browser builds (build/browser.esm.js in each package), which already contain their GPL-3.0 dependencies (wasmcurves, wasmbuilder, fastfile, r1csfile and @iden3/binfileutils). Those are named, with their versions, in each package's repository at the tag above, and their license comments are in the notices file.</p>",
    "    <h2>Every package bundled into the program</h2>",
    "    <ul>",
    ...manifest.packages.map(pk),
    "    </ul>",
    `    <p>Built from commit <code>${esc(manifest.commit)}</code> with esbuild ${esc(manifest.toolchain.esbuild)}. The same list, machine-readable: <a href="${esc(OFFER_URL + MANIFEST_NAME)}">${MANIFEST_NAME}</a>.</p>`,
    "  </body>",
    "</html>",
    "",
  ].join("\n");
}

/**
 * PURE (readFile injected, returns Buffers): the offer for one build. `layersFiles` are the bundle's Totem inputs
 * (layersInputsOf), `packages` the bundled packages (bundledPackagesOf). Every file is read byte for byte; a file that
 * cannot be read THROWS, and so does an empty GPL text — prover.js never ships without its offer.
 * Returns { manifest, outputs: [{ rel, bytes }] } (rel is relative to the offer folder).
 */
export function buildOffer({ layersFiles, buildFiles = BUILD_FILES, packages, gplText, commit, esbuildVersion, readFile }) {
  if (typeof gplText !== "string" || !gplText.includes("GNU GENERAL PUBLIC LICENSE")) throw new Error("the GPL-3.0 text (node_modules/snarkjs/COPYING) is missing or is not the license — prover.js cannot ship without its source offer");
  if (!Array.isArray(layersFiles) || layersFiles.length === 0) throw new Error("no Totem files to offer — the bundle's inputs were not read");
  const entry = (rel) => {
    if (!SAFE_REL.test(rel)) throw new Error(`the offer refuses to serve ${JSON.stringify(rel)}`);
    let bytes;
    try {
      bytes = readFile(rel);
    } catch (e) {
      throw new Error(`a file the offer must serve could not be read: ${rel} (${e && e.message ? e.message : e})`);
    }
    if (!Buffer.isBuffer(bytes)) bytes = Buffer.from(bytes);
    return { meta: { path: rel, url: servedUrlOf(rel), bytes: bytes.length, sha256: sha256Hex(bytes) }, bytes };
  };
  const files = [...layersFiles].sort().map(entry);
  const build = [...buildFiles].sort().map(entry);
  const pkgs = Array.isArray(packages) ? packages : [];
  const manifest = {
    offer: OFFER_SCHEMA,
    prover: "/device/prover.js",
    license: "GPL-3.0",
    licenseText: OFFER_URL + LICENSE_TEXT_NAME,
    notices: "/device/prover.js.LICENSE.txt",
    commit: typeof commit === "string" && commit ? commit : "unknown",
    files: files.map((f) => f.meta),
    build: build.map((f) => f.meta),
    upstream: pkgs.filter((p) => Object.prototype.hasOwnProperty.call(UPSTREAM, p.name)),
    packages: pkgs,
    toolchain: { esbuild: typeof esbuildVersion === "string" && esbuildVersion ? esbuildVersion : "unknown" },
  };
  const outputs = [
    ...files.map((f) => ({ rel: servedRelOf(f.meta.path), bytes: f.bytes })),
    ...build.map((f) => ({ rel: servedRelOf(f.meta.path), bytes: f.bytes })),
    { rel: LICENSE_TEXT_NAME, bytes: Buffer.from(gplText, "utf8") },
    { rel: MANIFEST_NAME, bytes: Buffer.from(JSON.stringify(manifest, null, 2) + "\n", "utf8") },
    { rel: "index.html", bytes: Buffer.from(indexHtml(manifest), "utf8") },
  ];
  return { manifest, outputs };
}

/** what is wrong with a notice page: any inline script, style block, style attribute or event handler, or a manifest
 *  entry it does not link. [] = fine. */
export function indexHtmlProblems(html, manifest) {
  const out = [];
  const s = String(html ?? "");
  if (/<script\b/i.test(s)) out.push("the notice page carries a <script>");
  if (/<style\b/i.test(s)) out.push("the notice page carries a <style> block");
  if (/\sstyle\s*=/i.test(s)) out.push("the notice page carries a style attribute");
  if (/\son[a-z]+\s*=/i.test(s)) out.push("the notice page carries an inline event handler");
  for (const e of [...((manifest && manifest.files) || []), ...((manifest && manifest.build) || [])]) if (!s.includes(`href="${esc(e.url)}"`)) out.push(`the notice page does not link ${e.path}`);
  if (manifest && !s.includes(`href="${esc(manifest.licenseText)}"`)) out.push("the notice page does not link the GPL-3.0 text");
  return out;
}

/**
 * PURE: what is wrong with an offer against the bundle it belongs to. `layersInputs` are the bundle's own Totem inputs
 * (from the metafile of THAT build). [] = it offers exactly what the bundle carries, each with a hash, and names both
 * GPL-3.0 packages with their tagged upstream source.
 */
export function offerProblems(manifest, layersInputs, { snarkjsVersion = null, ffjavascriptVersion = null } = {}) {
  const out = [];
  if (!manifest || typeof manifest !== "object") return ["no manifest"];
  if (manifest.offer !== OFFER_SCHEMA) out.push(`the manifest's schema is ${JSON.stringify(manifest.offer)}, not ${OFFER_SCHEMA}`);
  const offered = (manifest.files || []).map((f) => f && f.path);
  const want = [...new Set(layersInputs || [])].sort();
  const have = [...offered].sort();
  if (new Set(have).size !== have.length) out.push("the offer lists a file twice");
  for (const p of want) if (!have.includes(p)) out.push(`the bundle carries ${p}, but the offer does not serve it`);
  for (const p of have) if (!want.includes(p)) out.push(`the offer serves ${p}, which the bundle does not carry`);
  for (const f of [...(manifest.files || []), ...(manifest.build || [])]) {
    if (!f || !/^[0-9a-f]{64}$/.test(String(f.sha256 || ""))) out.push(`no sha256 for ${f && f.path}`);
    if (!f || f.url !== servedUrlOf(f.path)) out.push(`the served address of ${f && f.path} is not ${f && servedUrlOf(f.path)}`);
    if (!f || !Number.isInteger(f.bytes) || f.bytes <= 0) out.push(`no byte count for ${f && f.path}`);
  }
  for (const b of BUILD_FILES) if (!(manifest.build || []).some((f) => f && f.path === b)) out.push(`the offer does not serve the build file ${b}`);
  for (const name of Object.keys(UPSTREAM)) {
    const ups = (manifest.upstream || []).filter((p) => p && p.name === name);
    if (ups.length === 0) out.push(`the offer does not name ${name}'s upstream source`);
    for (const u of ups) if (u.source !== `${UPSTREAM[name]}/tree/v${u.version}`) out.push(`${name} ${u.version}: the source link ${JSON.stringify(u.source)} is not the tagged upstream`);
  }
  // the banner names one version of each; the bundle must carry exactly that version (the two cannot drift)
  if (snarkjsVersion !== null && !(manifest.upstream || []).some((u) => u.name === "snarkjs" && u.version === snarkjsVersion)) out.push(`the banner names snarkjs ${snarkjsVersion}, which the bundle does not carry`);
  if (ffjavascriptVersion !== null && !(manifest.upstream || []).some((u) => u.name === "ffjavascript" && u.version === ffjavascriptVersion)) out.push(`the banner names ffjavascript ${ffjavascriptVersion}, which the bundle does not carry`);
  if (typeof manifest.commit !== "string" || !manifest.commit) out.push("the manifest names no commit");
  if (manifest.licenseText !== OFFER_URL + LICENSE_TEXT_NAME) out.push("the manifest does not point at the GPL-3.0 text");
  return out;
}

/** write the offer folder from scratch (a stale file from an earlier build never survives) */
export function writeOffer(outDir, offer) {
  rmSync(outDir, { recursive: true, force: true });
  for (const o of offer.outputs) {
    const f = path.join(outDir, ...o.rel.split("/"));
    mkdirSync(path.dirname(f), { recursive: true });
    writeFileSync(f, o.bytes);
  }
}

/**
 * Read the WRITTEN offer back and compare it with the committed sources: every served file byte-equal to its source and
 * to its manifest hash, the GPL text present, the manifest on disk equal to the one built, the notice page clean and
 * complete. `readSource(rel)` reads a committed file. [] = what will be served is exactly the corresponding source.
 */
export function servedProblems({ outDir, manifest, readSource }) {
  const out = [];
  const read = (rel) => readFileSync(path.join(outDir, ...rel.split("/")));
  for (const e of [...(manifest.files || []), ...(manifest.build || [])]) {
    let served;
    try {
      served = read(servedRelOf(e.path));
    } catch {
      out.push(`${e.path} is not in the offer folder`);
      continue;
    }
    let src = null;
    try {
      src = readSource(e.path);
    } catch {
      out.push(`${e.path}: its committed source could not be read`);
    }
    if (src !== null && !Buffer.from(src).equals(served)) out.push(`${e.path}: the served copy differs from the committed source`);
    if (sha256Hex(served) !== e.sha256) out.push(`${e.path}: the served copy does not hash to its manifest entry`);
    if (served.length !== e.bytes) out.push(`${e.path}: the served copy is ${served.length} bytes, the manifest says ${e.bytes}`);
  }
  try {
    if (!read(LICENSE_TEXT_NAME).toString("utf8").includes("GNU GENERAL PUBLIC LICENSE")) out.push("the served GPL-3.0 text is not the license");
  } catch {
    out.push("the GPL-3.0 text is not in the offer folder");
  }
  try {
    const onDisk = JSON.parse(read(MANIFEST_NAME).toString("utf8"));
    if (JSON.stringify(onDisk) !== JSON.stringify(manifest)) out.push("the manifest on disk differs from the one built");
  } catch {
    out.push("the manifest is not in the offer folder");
  }
  try {
    out.push(...indexHtmlProblems(read("index.html").toString("utf8"), manifest));
  } catch {
    out.push("the notice page is not in the offer folder");
  }
  return out;
}

/**
 * For a DEPLOYMENT (scripts/smoke-deployed.mjs check 11): `fetchBytes(url)` → { status, bytes } for a same-site path.
 * Every manifest entry must answer 200 and hash to its entry; the GPL text must be the license; the notice page must
 * answer, be clean and link every entry. [] = the deployment serves its offer. Async; never throws on a bad answer.
 */
export async function deployedOfferProblems(manifest, fetchBytes, { expectFiles = null } = {}) {
  const out = [];
  if (!manifest || typeof manifest !== "object" || !Array.isArray(manifest.files)) return ["no readable manifest"];
  if (expectFiles !== null && manifest.files.length !== expectFiles) out.push(`the manifest lists ${manifest.files.length} Totem file(s), expected ${expectFiles}`);
  for (const e of [...manifest.files, ...(manifest.build || [])]) {
    if (!e || typeof e.url !== "string" || !e.url.startsWith(OFFER_URL)) {
      out.push(`an entry is not served from ${OFFER_URL}: ${JSON.stringify(e && e.url)}`);
      continue;
    }
    let r;
    try {
      r = await fetchBytes(e.url);
    } catch (err) {
      out.push(`${e.url}: ${err && err.message ? err.message : err}`);
      continue;
    }
    if (r.status !== 200) out.push(`${e.url} answered ${r.status}`);
    else if (sha256Hex(r.bytes) !== e.sha256) out.push(`${e.url} does not hash to its manifest entry`);
  }
  for (const name of Object.keys(UPSTREAM)) {
    const ups = (manifest.upstream || []).filter((p) => p && p.name === name);
    if (ups.length === 0 || ups.some((u) => !/^\d+\.\d+\.\d+/.test(String(u.version)) || u.source !== `${UPSTREAM[name]}/tree/v${u.version}`)) out.push(`the manifest does not name ${name} with a version and its tagged upstream source`);
  }
  try {
    const g = await fetchBytes(manifest.licenseText);
    if (g.status !== 200 || !Buffer.from(g.bytes).toString("utf8").includes("GNU GENERAL PUBLIC LICENSE")) out.push(`${manifest.licenseText} does not answer the GPL-3.0 text`);
  } catch (err) {
    out.push(`${manifest.licenseText}: ${err && err.message ? err.message : err}`);
  }
  try {
    const h = await fetchBytes(OFFER_URL);
    if (h.status !== 200) out.push(`${OFFER_URL} answered ${h.status}`);
    else out.push(...indexHtmlProblems(Buffer.from(h.bytes).toString("utf8"), manifest));
  } catch (err) {
    out.push(`${OFFER_URL}: ${err && err.message ? err.message : err}`);
  }
  return out;
}
