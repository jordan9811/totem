// BROWSER KEYSTORE PASS Gate 1 stage 3 — generates lib/device/routes.generated.ts: the table of API route handlers the
// browser device answers in-process (docs/custody-model.md D-CU-0-3). Every app/api/**/route.ts is included except
// the ones that are the SERVER's by nature (its liveness, its live diagnostics); those fall through the fetch patch
// to the Next server. Re-run after adding a route: `node scripts/device-routes.mjs`.
import { readdirSync, statSync, writeFileSync, readFileSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const API = path.join(ROOT, "app", "api");
const OUT = path.join(ROOT, "lib", "device", "routes.generated.ts");

/** the server keeps these: its own liveness and the operator's live diagnostics. FC-READ: "fc/read" is the live-read
 *  relay — it holds the Neynar read key, so the device must forward it to the server (and never bundle it); keep
 *  public/device/boot.js's default list equal to this set. CONNECT MAIN: "fc/connect" is the owner service's QR flow
 *  (it reads the connector account's custody key by name, talks to Neynar and the chain, and refuses on a public
 *  deployment): a browser has no use for it, so it stays out of the bundle and the server answers its own refusal. */
// CONNECTOR SETUP (verify): "fc/connector" is the connector account's own setup (viem's secp256k1 signer, the
// register/fname flow) — owner service only, so it stays out of the public browser bundle like "fc/connect"; the
// prefix rule is exact-or-child, so naming it is the only way (fc/connect does not cover fc/connector)
const SERVER_ONLY = new Set(["health", "dev/live", "custody/passkey/challenge", "custody/passkey/release", "owner-login", "fc/read", "fc/connect", "fc/connector"]);
/** OWNER PASSKEYS (D-OWNER-PASSKEYS): an entry covers its whole subtree, exactly as the device's fetch patch already
 *  treats it (public/device/boot.js and lib/device/host.ts send "/api/<entry>" AND "/api/<entry>/…" to the server).
 *  "owner-login" therefore keeps /api/owner-login/passkey/options, …/passkey/verify, …/security and …/state out of the
 *  browser bundle too — they read the owner app's volume (node:fs) and have no meaning in a browser. No route that
 *  existed before sits under an entry, so the device's route table is unchanged by this. */
const isServerOnly = (rel) => [...SERVER_ONLY].some((p) => rel === p || rel.startsWith(p + "/"));

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const p = path.join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (name === "route.ts") out.push(p);
  }
  return out;
}

const routes = walk(API)
  .map((file) => path.relative(API, path.dirname(file)).split(path.sep).join("/"))
  .filter((rel) => !isServerOnly(rel))
  .sort((a, b) => {
    // static before dynamic, then longest first — the matcher takes the first regex that fits
    const da = a.includes("["), db = b.includes("[");
    if (da !== db) return da ? 1 : -1;
    return b.length - a.length || a.localeCompare(b);
  });

const lines = [
  "// GENERATED by scripts/device-routes.mjs — do not edit. The API routes the browser device answers in-process.",
  "/* eslint-disable */",
];
routes.forEach((rel, i) => lines.push(`import * as r${i} from "@/app/api/${rel}/route";`));
lines.push("");
lines.push("export interface DeviceRoute { pattern: string; re: RegExp; params: string[]; mod: Record<string, unknown> }");
lines.push("export const ROUTES: DeviceRoute[] = [");
routes.forEach((rel, i) => {
  const params = [...rel.matchAll(/\[(\w+)\]/g)].map((m) => m[1]);
  const re = "^/api/" + rel.replace(/[.*+?^${}()|\\]/g, "\\$&").replace(/\[(\w+)\]/g, "([^/]+)") + "$";
  lines.push(`  { pattern: "/api/${rel}", re: new RegExp(${JSON.stringify(re)}), params: ${JSON.stringify(params)}, mod: r${i} as Record<string, unknown> },`);
});
lines.push("];");
lines.push(`export const SERVER_ONLY_ROUTES = ${JSON.stringify([...SERVER_ONLY].map((r) => "/api/" + r))};`);
lines.push("");
const body = lines.join("\n");
if (!existsSync(OUT) || readFileSync(OUT, "utf8") !== body) {
  writeFileSync(OUT, body);
  console.log(`[device-routes] wrote ${path.relative(ROOT, OUT)}: ${routes.length} device routes, ${SERVER_ONLY.size} server-only`);
} else {
  console.log(`[device-routes] unchanged: ${routes.length} device routes`);
}
