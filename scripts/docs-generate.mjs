function roadmapData() {
  const dir = join(ROOT, "docs/internal/passes");
  const items = [];
  for (const f of readdirSync(dir).filter((x) => x.endsWith(".md") && x !== "index.md").sort()) {
    const text = readFileSync(join(dir, f), "utf8").replace(/\r\n/g, "\n");
    const fm = /^---\n([\s\S]*?)\n---/.exec(text)?.[1] ?? "";
    const title = (/^title:\s*(.*)$/m.exec(fm)?.[1]?.trim() ?? f).replace(/^"(.*)"$/, "$1").replace(/\\"/g, '"');
    const report = /^report:\s*(.*)$/m.exec(fm)?.[1]?.trim() ?? "";
    for (const m of text.matchAll(/^\s*[-*]\s+\*\*\[([A-Z-]+)\]\*\*\s+(.*)$/gm)) {
      if (!STATUS_VOCAB.includes(m[1])) continue;
      const body = m[2].replace(/\{cite:[^}]*\}/g, "").trim();
      const cite = /\{cite:\s*([^>{}]+?)\s*>\s*(?:"([^"]+)"|'([^']+)')\s*\}/.exec(m[2]);
      items.push({ status: m[1], text: body, area: areaOf(body), pass: f.replace(/\.md$/, ""), passTitle: title, source: cite ? `${cite[1].trim()} › ${cite[2] ?? cite[3]}` : report });
    }
  }
  const extraPath = join(ROOT, "docs/internal/roadmap-extra.json");
  const extra = existsSync(extraPath) ? JSON.parse(readFileSync(extraPath, "utf8")) : [];
  for (const e of extra) items.push({ status: e.status, text: e.text, area: e.area ?? areaOf(e.text), pass: e.pass ?? "seeded", passTitle: e.passTitle ?? "Seeded item", source: e.source ?? "docs/internal/roadmap-extra.json" });
  const counts = {};
  for (const it of items) counts[it.status] = (counts[it.status] ?? 0) + 1;
  const concepts = [
    ["Root & personas", /\b(persona|root|custody|keystore|vault|recovery|device|roster)\b/i],
    ["Disclosure & grants", /\b(grant|disclosure|unlock|facet|linkage surface|inner circle)\b/i],
    ["Forking", /\b(fork|continuity|carry)\b/i],
    ["Reputation & UBI", /\b(rep\b|reputation|tier|stake|allowance|ubi|accrual|influence)\b/i],
    ["Attestations", /\b(attestation|issuer|bucket|honou?r)\b/i],
    ["Lenses", /\b(lens|algo|algorithm|ranking|signals?)\b/i],
  ];
  const distance = concepts.map(([name, re]) => {
    const hits = items.filter((it) => re.test(it.text));
    const c = {};
    for (const it of hits) c[it.status] = (c[it.status] ?? 0) + 1;
    return { concept: name, counts: c, total: hits.length };
  });
  const data = { generatedAt: new Date().toISOString().slice(0, 10), statuses: STATUS_VOCAB, areas: [...new Set(items.map((i) => i.area))].sort(), counts, distance, items };
  wr("docs/internal/roadmap-data.json", JSON.stringify(data, null, 2));
  return data;
}

// ---------------------------------------------------------------- open issues
function openIssuesGenerated() {
  const reports = readdirSync(join(ROOT, "notes/reports")).filter((f) => /^REPORT(-[A-Z0-9]+)?\.md$/.test(f)).sort().map((f) => "notes/reports/" + f);
  let out = GEN("REPORT-*.md and notes/runbooks/MORNING.md") + "";
  out += "## KNOWN-BROKEN, across every report\n\nEvery section of every report whose heading names KNOWN-BROKEN, verbatim in outline; a report that says \"none\" is listed as such.\n\n";
  for (const f of reports) {
    const text = rd(f);
    const lines = text.split("\n");
    const heads = [];
    for (let i = 0; i < lines.length; i++) { const m = /^(#{1,6})\s+(.*)$/.exec(lines[i]); if (m && /KNOWN-BROKEN/i.test(m[2])) heads.push({ level: m[1].length, i, h: m[2].trim() }); }
    const noneLines = lines.filter((l) => /KNOWN-BROKEN:\s*none/i.test(l) || /No (feature|crypto safety item) (was|is) (marked )?KNOWN-BROKEN/i.test(l) || /nothing KNOWN-BROKEN/i.test(l));
    out += `### ${f}\n\n`;
    if (!heads.length && !noneLines.length) { out += "- no KNOWN-BROKEN section or line\n\n"; continue; }
    for (const h of heads) {
      const end = lines.slice(h.i + 1).findIndex((l) => new RegExp(`^#{1,${h.level}}\\s`).test(l));
      const body = lines.slice(h.i + 1, end === -1 ? lines.length : h.i + 1 + end);
      // a bullet plus its wrapped continuation lines (reports wrap at ~80 columns)
      const clean = [];
      let open = false;
      for (const l of body) {
        if (/^\s*[-*]\s+|^\s*\d+\.\s+/.test(l)) { clean.push(l.trim().replace(/^[-*]\s+/, "").replace(/^\d+\.\s+/, "")); open = true; }
        else if (!l.trim() || /^#/.test(l)) open = false;
        else if (open) clean[clean.length - 1] += " " + l.trim();
      }
      out += `- **${h.h}** {cite: ${f} > "${h.h}"}\n`;
      for (const b of clean.slice(0, 12)) out += `  - ${b.replace(/\{cite:[^}]*\}/g, "").slice(0, 240)}\n`;
      if (!clean.length) { const prose = body.map((l) => l.trim()).filter(Boolean).slice(0, 2).join(" "); if (prose) out += `  - ${prose.slice(0, 240)}\n`; }
    }
    for (const l of noneLines.slice(0, 2)) out += `- ${l.trim().slice(0, 200)}\n`;
    out += "\n";
  }
  if (existsSync(join(ROOT, "notes/runbooks/MORNING.md"))) {
    const m = rd("notes/runbooks/MORNING.md");
    const title = /^#\s+(.*)$/m.exec(m)?.[1] ?? "notes/runbooks/MORNING.md";
    out += `## notes/runbooks/MORNING.md items (${title})\n\nThe hand-off brief's numbered items, first line of each. {cite: notes/runbooks/MORNING.md > "${title}"}\n\n`;
    for (const it of m.matchAll(/^(\d+)\.\s+\*\*(.*?)\*\*\s*(.*)$/gm)) out += `- **${it[1]}. ${it[2]}** ${it[3].trim().slice(0, 200)}\n`;
    out += "\n";
  }
  wr("docs/internal/open-issues-generated.md", out);
}

