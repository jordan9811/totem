// ---------------------------------------------------------------- data model
function dataModelPage() {
  const vault = rd("lib/vault/vault.ts");
  const sealedBlock = /VAULT_NAMESPACES[^=]*=\s*new Set\(\[([\s\S]*?)\]\)/.exec(vault)?.[1] ?? "";
  const sealed = [...sealedBlock.matchAll(/"(\w+)"/g)].map((m) => m[1]);
  const persist = rd("lib/adapters/mock/persist.ts");
  const unionBlock = /type Namespace\s*=([\s\S]*?);/.exec(persist)?.[1] ?? "";
  const all = [...unionBlock.matchAll(/"(\w+)"/g)].map((m) => m[1]);
  const extraBlock = /type ExtraNamespace\s*=([\s\S]*?);/.exec(persist)?.[1] ?? "";
  const extra = [...extraBlock.matchAll(/"(\w+)"/g)].map((m) => m[1]);
  const namespaces = [...new Set([...all, ...extra])].sort();
  const plain = namespaces.filter((n) => !sealed.includes(n));
  const tables = new Set();
  for (const f of ["validator/db.js", "validator/migrations.js"]) for (const m of rd(f).matchAll(/CREATE TABLE(?: IF NOT EXISTS)? (\w+)/g)) tables.add(m[1]);
  const dropped = new Set([...rd("validator/migrations.js").matchAll(/DROP TABLE (\w+)/g)].map((m) => m[1]));
  const renamed = [...rd("validator/migrations.js").matchAll(/ALTER TABLE (\w+) RENAME TO (\w+)/g)];
  for (const r of renamed) { tables.delete(r[1]); tables.add(r[2]); }
  for (const d of dropped) if (!renamed.some((r) => r[2] === d)) tables.delete(d);
  let out = GEN("lib/vault/vault.ts, lib/adapters/mock/persist.ts, validator/db.js, validator/migrations.js") + "# Data model (rendered from source)\n\n";
  out += "The validator stores two kinds of thing: SQL tables it can read (public rows: rep events, stakes, zk registrations and eligibility, attestations, anonymous casts) and state namespaces the app persists through it. A namespace is either PLAIN (the validator can read the JSON) or SEALED (one AES-256-GCM record per namespace, padded to a KiB step, whose key never leaves the device). Which is which is decided in one place, `lib/vault/vault.ts`; this page renders that decision.\n\n";
  out += `## Sealed namespaces (${sealed.length})\n\nThe validator holds ciphertext and an address, nothing else.\n\n`;
  for (const n of sealed) out += `- \`${n}\`\n`;
  out += `\n## Plain namespaces (${plain.length})\n\nThe validator can read these. Every one of them is public-by-design state (modes, rules, folders, public lens artifacts, attestations, cursors) or a per-persona record that carries no root.\n\n`;
  for (const n of plain) out += `- \`${n}\`\n`;
  out += `\n## Validator tables (${tables.size})\n\n`;
  for (const t of [...tables].sort()) out += `- \`${t}\`\n`;
  out += "\n## Deliberately absent\n\nThings the validator has NO column, row or namespace for, on purpose. Each one is a link an operator could otherwise make; the linkage tests (v1–v5) assert their absence on every sweep.\n\n";
  out += "- a persona → root map (removed in ZK pass 2, migration 006; the validator learns which personas exist, not whose they are)\n";
  out += "- a root balance of influence allowance (the vault holds it; the validator sees per-persona stake rows only)\n";
  out += "- a scroll-zone layout, a button binding, a search query or a search index (device-local; the index is re-derived from the vault)\n";
  out += "- a DM's text, tweet id or sender beyond the persona's own attested handle (the bookmark is an opaque hash; the item is sealed)\n";
  out += "- a relationship-port record or a pending grant in plaintext (sealed)\n";
  out += "- a custody address, signer key, registrant or funder for any persona account (the fid map is sealed; the plain map holds fid + fname)\n";
  out += "- a private post's text (sealed), or any row that names two personas of one root together\n";
  wr("docs/technical/data-model.md", out);
}

