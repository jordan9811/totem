const cell = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\r?\n/g, " ").trim();
const normStatus = (raw) => String(raw ?? "").toLowerCase().replace(/[^a-z]/g, "");

function legendOf(raw, where) {
  const hit = LEGEND.find((l) => l.match.test(normStatus(raw)));
  if (!hit) throw new Error(`docs:generate: ${where} has status "${raw}", which is not one of the docs legend's words (${LEGEND.map((l) => l.label).join(" / ")}). Map it in LEGEND in scripts/docs-generate.mjs; a guessed status is never written.`);
  return hit;
}

/** the strict-JSON blocks between `@status-json:<name>:begin` and `:end` markers, by name */
function statusJsonBlocks(text, src) {
  const blocks = {};
  for (const m of text.matchAll(/\/\*\s*@status-json:([\w-]+):begin\s*\*\/([\s\S]*?)\/\*\s*@status-json:\1:end\s*\*\//g)) {
    try { blocks[m[1]] = JSON.parse(m[2]); } catch (e) { throw new Error(`docs:generate: ${src} block "${m[1]}" is not strict JSON (${e.message}); nothing was written`); }
  }
  return blocks;
}

async function whatWorksToday() {
  const out = "docs/start/what-works-generated.md";
  mkdirSync(join(ROOT, "docs/start"), { recursive: true });
  // DOCS_STATUS_FILE points the generator at another file (the generator's own test uses a sample); unset in builds
  const candidates = process.env.DOCS_STATUS_FILE ? [process.env.DOCS_STATUS_FILE] : ["lib/status/features.ts", "lib/status/features.json"];
  const src = candidates.find((p) => existsSync(resolve(ROOT, p)));
  if (!src) {
    const msg = `the status file is missing (${candidates.join(" or ")}); the docs home shows a warning in place of the table`;
    if (process.env.DOCS_REQUIRE_STATUS === "1") throw new Error("docs:generate: " + msg + ", and DOCS_REQUIRE_STATUS=1 refuses to publish without it");
    console.warn("  WARN  " + msg);
    wr(out, GEN(candidates[0]) + "::: warning The status list did not generate\nThis table is generated from `" + candidates[0] + "`, the one status file the app's Help page also reads. This build could not find it, so nothing is listed here rather than a guess. Every feature page still opens with its own status box: start with [all features](/features/).\n:::\n");
    return 0;
  }
  const text = readFileSync(resolve(ROOT, src), "utf8");
  const isList = (v) => Array.isArray(v) && v.length > 0 && v.every((x) => x && typeof x === "object");
  let list;
  let fileLegend = null;
  const blocks = src.endsWith(".json") ? {} : statusJsonBlocks(text, src);
  if (isList(blocks.features)) {
    list = blocks.features;
    fileLegend = isList(blocks.legend) ? blocks.legend : null;
  } else {
    let mod;
    if (src.endsWith(".json")) mod = { default: JSON.parse(text) };
    else mod = await import(pathToFileURL(resolve(ROOT, src)).href);
    const named = ["FEATURES", "FEATURE_STATUS", "STATUS", "features", "status", "default"];
    list = named.map((k) => mod[k]).find(isList);
    if (!list && mod.default && typeof mod.default === "object") list = Object.values(mod.default).find(isList);
    if (!list) list = Object.values(mod).find((v) => isList(v) && v.some((x) => pick(x, ["status", "state", "level"]) !== undefined));
    fileLegend = isList(mod.LEGEND) ? mod.LEGEND : null;
  }
  if (!list) throw new Error(`docs:generate: ${src} exports no list of features (an array of objects with a status); nothing was written`);
  // the file's own legend must use the docs' word for every status it defines, or Help and the docs say different things
  if (fileLegend) for (const l of fileLegend) {
    const id = pick(l, ["id", "key", "status"]);
    const label = pick(l, ["label", "name", "title"]);
    if (id === undefined || label === undefined) continue;
    const ours = legendOf(id, `${src} legend "${id}"`).label;
    if (normStatus(ours) !== normStatus(label)) throw new Error(`docs:generate: ${src} labels status "${id}" as "${label}", but the docs legend calls it "${ours}". Make the two agree; nothing was written.`);
  }
  const rows = list.map((f, i) => {
    const name = pick(f, ["name", "title", "label", "feature"]);
    if (!name) throw new Error(`docs:generate: ${src} entry ${i} has no name`);
    const id = pick(f, ["id", "key"]);
    const docs = pick(f, ["docs", "docsPath", "doc", "docsLink"]) ?? (id ? DOCS_PAGE[id] : undefined);
    const note = pick(f, ["today", "line", "detail", "summary", "description", "text", "what"]);
    const missing = pick(f, ["missing", "next", "todo"]);
    const pub = pick(f, ["public", "publicSite", "preview"]);
    const own = pick(f, ["owner", "ownerService", "private"]);
    const status = pick(f, ["status", "state", "level"]);
    const where = `${src} "${name}"`;
    const perSurface = status && typeof status === "object";
    const split = typeof pub === "string" || typeof own === "string" || perSurface;
    // a surface the entry does not name takes the entry's single status, if it has one
    const surface = (direct, keys) => (typeof direct === "string" ? direct : perSurface ? pick(status, keys) : status);
    const chip = (raw, w) => { const l = legendOf(raw, w); return `${l.mark} ${l.label}`; };
    return {
      name: typeof docs === "string" && docs.startsWith("/") ? `[${cell(name)}](${docs})` : cell(name),
      note: cell(note),
      missing: cell(missing),
      split,
      pub: split ? chip(surface(pub, ["public", "publicSite", "preview"]), where + " (public site)") : "",
      own: split ? chip(surface(own, ["owner", "ownerService", "private"]), where + " (owner's service)") : "",
      today: split ? "" : chip(status, where),
    };
  });
  const anySplit = rows.some((r) => r.split);
  const anyMissing = rows.some((r) => r.missing);
  let md = GEN(src);
  const head = anySplit ? ["Feature", "Public preview", "Owner's private service"] : ["Feature", "Today"];
  head.push("What it is");
  if (anyMissing) head.push("Still missing");
  md += `| ${head.join(" | ")} |\n|${head.map(() => "---").join("|")}|\n`;
  for (const r of rows) {
    const cells = anySplit ? [r.name, r.split ? r.pub : r.today, r.split ? r.own : r.today] : [r.name, r.today];
    cells.push(r.note);
    if (anyMissing) cells.push(r.missing);
    md += `| ${cells.join(" | ")} |\n`;
  }
  const checked = /STATUS_CHECKED_ON\s*=\s*"([\d-]+)"/.exec(text)?.[1];
  md += `\n_${rows.length} features, from \`${src}\`${checked ? `, last checked against the running sites on ${checked}` : ""}: the same list the app's Help page shows._\n`;
  wr(out, md);
  return rows.length;
}

