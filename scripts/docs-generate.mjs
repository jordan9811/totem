// ---------------------------------------------------------------- adapters
function adaptersPage() {
  const src = rd("lib/adapters/types.ts");
  const lines = src.split("\n");
  const ifaces = [];
  for (let i = 0; i < lines.length; i++) {
    const m = /^export interface (\w+Adapter)\s*\{/.exec(lines[i]);
    if (!m) continue;
    // the doc comment right above the interface
    let doc = [];
    for (let k = i - 1; k >= 0 && /^\s*(\/\*\*|\*|\/\/)/.test(lines[k]); k--) doc.unshift(lines[k].replace(/^\s*(\/\*\*|\*\/|\*|\/\/)\s?/, "").trim());
    const methods = [];
    let pending = [];
    let sig = "";
    for (let j = i + 1; j < lines.length && !/^\}/.test(lines[j]); j++) {
      const l = lines[j];
      if (/^\s*\/\*\*/.test(l) || /^\s*\*/.test(l) || /^\s*\/\//.test(l)) { pending.push(l.replace(/^\s*(\/\*\*|\*\/|\*|\/\/)\s?/, "").replace(/\*\/\s*$/, "").trim()); continue; }
      sig += (sig ? " " : "") + l.trim();
      if (/;\s*$/.test(l)) {
        const mm = /^(\w+)\s*(\(.*)$/.exec(sig);
        if (mm) methods.push({ name: mm[1], sig: sig.replace(/\s+/g, " "), doc: pending.filter(Boolean).join(" ") });
        sig = "";
        pending = [];
      }
    }
    ifaces.push({ name: m[1], doc: doc.filter((d) => d && !/^-{3,}/.test(d)).join(" "), methods });
  }
  const reg = rd("lib/adapters/registry.ts");
  const bindings = [];
  for (const m of reg.matchAll(/const (\w+)\s*=\s*\(?process\.env\.(ADAPTER_\w+)\s*(?:\?\?\s*"(\w+)"|===\s*"(\w+)"\s*\?\s*"(\w+)"\s*:\s*"(\w+)")/g)) {
    bindings.push({ env: m[2], def: m[3] ?? m[6], choices: m[3] ? undefined : `${m[4]} | ${m[6]}` });
  }
  const repChoices = /type RepImpl\s*=\s*([^;]+);/.exec(reg)?.[1]?.replace(/\s+/g, " ").replace(/"/g, "").trim();
  const repBinding = bindings.find((b) => b.env === "ADAPTER_REP");
  if (repBinding && repChoices && !repBinding.choices) repBinding.choices = repChoices;
  const persistedMaps = [];
  for (const m of reg.matchAll(/^\s+(\w+):\s*persisted\((\w+),\s*\{([\s\S]*?)\n\s*\}\)/gm)) {
    const entries = [...m[3].matchAll(/^\s*(\w+):\s*\[([^\]]*)\]/gm)].map((e) => `${e[1]} → ${e[2].replace(/"/g, "").split(",").map((s) => s.trim()).filter(Boolean).join(", ")}`);
    persistedMaps.push({ slot: m[1], impl: m[2], entries });
  }
  const snapshotBody = /function registrySnapshot\(\)[\s\S]*?return \{([\s\S]*?)\n\s*\};/.exec(reg)?.[1] ?? "";
  const snapshot = [...snapshotBody.matchAll(/^\s+(\w+):\s*(personaImpl|currentRepImpl\(\)|identityImpl|"mock")/gm)].map((m) => ({ slot: m[1], value: m[2] }));
  let out = GEN("lib/adapters/types.ts and lib/adapters/registry.ts") + "# Adapters (rendered from source)\n\n";
  out += "Every side effect in the app goes through one of these seams. The app is written against the interface; the registry binds each slot to a mock, the validator, or the proof-mediated implementation. Read `lib/adapters/types.ts` for the types; this page is a rendering of it.\n\n";
  out += "## Bindings\n\n| Slot | Bound to | Chosen by |\n|---|---|---|\n";
  for (const s of snapshot) {
    const b = s.value === "personaImpl" ? bindings.find((x) => x.env === "ADAPTER_PERSONA") : s.value === "currentRepImpl()" ? bindings.find((x) => x.env === "ADAPTER_REP") : s.value === "identityImpl" ? bindings.find((x) => x.env === "ADAPTER_IDENTITY") : null;
    out += `| \`${s.slot}\` | ${b ? `env-selected (default \`${b.def}\`${b.choices ? `; ${b.choices}` : ""})` : "mock (persisted through the validator state namespaces)"} | ${b ? `\`${b.env}\`` : "fixed"} |\n`;
  }
  out += "\n## Which method dirties which validator namespace\n\nThe mock adapters are wrapped by `persisted()`: after a listed method runs, the named namespaces are flushed to the validator (sealed ones as ciphertext). A method not listed here writes nothing server-side.\n\n";
  for (const p of persistedMaps) { out += `### \`${p.slot}\` (${p.impl})\n\n`; for (const e of p.entries) out += `- ${e}\n`; out += "\n"; }
  out += "## Interfaces\n\n";
  for (const i of ifaces) {
    out += `### ${i.name}\n\n`;
    if (i.doc) out += i.doc + "\n\n";
    out += "| Method | Signature | Note |\n|---|---|---|\n";
    for (const m of i.methods) out += `| \`${m.name}\` | \`${m.sig.replace(/\|/g, "\\|")}\` | ${m.doc.replace(/\|/g, "\\|")} |\n`;
    out += "\n";
  }
  out += `_${ifaces.length} interfaces, ${ifaces.reduce((n, i) => n + i.methods.length, 0)} methods._\n`;
  wr("docs/technical/adapters.md", out);
}

