// A small dependency-free QR encoder (ISO/IEC 18004 model 2: byte mode, ECC level M, versions 1-40, the standard mask
// penalty). Verified against two independent decoders (zxing-cpp and OpenCV) across every version and ECC level —
// the overnight unit harness re-checks the approval URL's symbol the same way.

type Ecl = "L" | "M" | "Q" | "H";
const ECL_INDEX: Record<Ecl, number> = { L: 0, M: 1, Q: 2, H: 3 };
const ECL_FORMAT_BITS: Record<Ecl, number> = { L: 1, M: 0, Q: 3, H: 2 };
// prettier-ignore
